"""The scores: computing every route's `disclosure_rating:` and `carbon_intensity:` and every organization's
`disclosure_rating:`, and writing them at the end of their files as ordinary fields. `python -m build score` runs it;
see score() below. Each grid's intensity is read from its file, where `python -m build grid-emissions --write` wrote it at
curation time (build/grid_emissions.py): score never loads Ember's table.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path
from typing import Any, cast

import yaml

from build.carbon_intensity import carbon_intensity
from build.constants.snapshots import CLOUD_REGIONS_FILE
from build.disclosure_rating import disclosure_rating, organization_rating
from build.load_sources import load_cloud_regions, load_sources
from build.schemas.disclosure_rating import Letter
from build.schemas.grid import Grid
from build.schemas.route import Route
from build.schemas.score import OrgRating, RouteScore
from build.types import ScoreRun, Sources
from build.validate import validate_sources


# The line above the fields score writes, at the end of each route and organization file.
GENERATED_COMMENT = "# Generated by `python -m build score`. Everything below this line is rewritten on each run; do not edit it by hand."


def route_text(file_text: str, route_score: RouteScore) -> str:
    """A route file's text ending with GENERATED_COMMENT, its disclosure_rating: and its carbon_intensity:. Everything
    below the comment is replaced; everything above it is kept byte for byte (the file is never loaded and dumped)."""
    kept = file_text.partition(GENERATED_COMMENT)[0].rstrip()
    disclosure = yaml.safe_dump(
        {"disclosure_rating": dict(route_score["disclosure_rating"])},
        sort_keys=False,
        allow_unicode=True,
    )
    carbon = yaml.safe_dump(
        {"carbon_intensity": dict(route_score["carbon_intensity"])},
        sort_keys=False,
        allow_unicode=True,
    )
    return kept + "\n\n" + GENERATED_COMMENT + "\n" + disclosure + "\n" + carbon


def org_text(file_text: str, org_rating: OrgRating) -> str:
    """An organization file's text ending with GENERATED_COMMENT and its disclosure_rating:. Everything below the
    comment is replaced; everything above it is kept byte for byte (the file is never loaded and dumped)."""
    kept = file_text.partition(GENERATED_COMMENT)[0].rstrip()
    disclosure = yaml.safe_dump({"disclosure_rating": dict(org_rating)}, sort_keys=False, allow_unicode=True)
    return kept + "\n\n" + GENERATED_COMMENT + "\n" + disclosure


def checked_sources(
    root: Path,
) -> tuple[list[str], Sources, dict[tuple[str, str], list[str]]]:
    """sources/ and the cloud-region table, read and checked against each other."""
    data = load_sources(root)
    cloud_path = root / CLOUD_REGIONS_FILE
    cloud = load_cloud_regions(cloud_path) if cloud_path.exists() else {}
    errors = validate_sources(data, cloud_regions=cloud)
    return errors, cast(Sources, data), cloud


def route_grids(
    route: Route,
    grids: Mapping[str, Grid],
    cloud_regions: Mapping[tuple[str, str], list[str]],
) -> dict[str, Grid]:
    """The grid files a route's candidates resolve to, sorted by name: a grid: candidate names its file, a cloud:
    candidate resolves through the cloud-region table to its zones and each zone to the grid file that claims it.
    Validation has checked that every candidate resolves."""
    zones = {g["zone"]: name for name, g in grids.items() if "zone" in g}
    names: set[str] = set()
    for candidate in route["location"]["candidates"]:
        kind, _, rest = candidate.partition(":")
        if kind == "grid":
            names.add(rest)
        else:
            vendor, _, region = rest.partition(":")
            names |= {zones[zone] for zone in cloud_regions[(vendor, region)]}
    return {name: grids[name] for name in sorted(names)}


def score_routes(
    data: Sources,
    cloud_regions: Mapping[tuple[str, str], list[str]],
) -> dict[str, RouteScore]:
    """The fields score writes for every route: its disclosure letter and its carbon intensity, as they are stored. The
    carbon intensity reads each grid's stored intensity: (validation has checked every grid has one)."""
    route_scores: dict[str, RouteScore] = {}
    for name, route in sorted(data["routes"].items()):
        grids = route_grids(route, data["grids"], cloud_regions)
        route_scores[name] = RouteScore(
            disclosure_rating=disclosure_rating(route["location"], grids),
            # Validation has checked every grid has its intensity:, so none is left out here.
            carbon_intensity=carbon_intensity(
                data["models"][route["model"]],
                {g: grid["intensity"] for g, grid in grids.items() if "intensity" in grid},
            ),
        )
    return route_scores


def score_organizations(data: Sources, route_scores: Mapping[str, RouteScore]) -> dict[str, OrgRating]:
    """Every organization's disclosure_rating:, from the letters of the routes naming it, as it is stored."""
    org_ratings: dict[str, OrgRating] = {}
    for name in sorted(data["organizations"]):
        letters: list[Letter] = [
            route_scores[r]["disclosure_rating"]["letter"]
            for r in sorted(route_scores)
            if data["routes"][r]["org"] == name
        ]
        org_ratings[name] = organization_rating(letters)
    return org_ratings


def change_routes(root: Path, route_scores: Mapping[str, RouteScore]) -> dict[Path, str]:
    """Each route file whose disclosure_rating: or carbon_intensity: would change, with its new text, in order."""
    changes: dict[Path, str] = {}
    for name in sorted(route_scores):
        path = root / "sources" / "routes" / f"{name}.yaml"
        text = path.read_text(encoding="utf-8")
        new = route_text(text, route_scores[name])
        if new != text:
            changes[path] = new
    return changes


def change_orgs(root: Path, org_ratings: Mapping[str, OrgRating]) -> dict[Path, str]:
    """Each organization file whose disclosure_rating: would change, with its new text, in order."""
    changes: dict[Path, str] = {}
    for name in sorted(org_ratings):
        path = root / "sources" / "organizations" / f"{name}.yaml"
        text = path.read_text(encoding="utf-8")
        new = org_text(text, org_ratings[name])
        if new != text:
            changes[path] = new
    return changes


def score(
    root: Path,
    *,
    write: bool = True,
) -> ScoreRun:
    """python -m build score: check sources/ against the outside data and write every field it computes whose
    value changed. Writes nothing if there are errors.

    write=False is what the CI gates run: nothing written, so the scores are computed from the committed files;
    `written` lists the files score would write."""
    errors, sources, cloud = checked_sources(root)
    if errors:
        return ScoreRun(errors, [])
    route_scores = score_routes(sources, cloud)
    org_ratings = score_organizations(sources, route_scores)
    changes = {**change_orgs(root, org_ratings), **change_routes(root, route_scores)}
    if write:
        for path, text in changes.items():
            path.write_text(text, encoding="utf-8")
    return ScoreRun([], list(changes), sources, route_scores, org_ratings)
